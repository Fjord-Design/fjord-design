"""Generate opaque Neovim colourschemes from Fjord's shared semantic contract."""

import argparse
import json
from pathlib import Path
import re
import sys

from fjord_tokens.adapters import map_adapter, write_adapter_files
from fjord_tokens.dtcg import TokenError, color_from_hex
from fjord_tokens.project import contrast_value

ROOT = Path(__file__).resolve().parents[2]
HEX = re.compile(r"#[0-9a-f]{6}")
GROUP = re.compile(r"(@?[A-Za-z][A-Za-z0-9_.]*)\.(fg|bg|sp)")


def highlights(values, mapping):
    groups, terminal = {}, {}
    for target, value in sorted(values.items()):
        if not isinstance(value, str) or not HEX.fullmatch(value):
            raise TokenError(f"Neovim {target}: expected opaque sRGB HEX")
        if target.startswith("terminal_color_"):
            suffix = target.removeprefix("terminal_color_")
            if not suffix.isdigit() or str(int(suffix)) != suffix or not 0 <= int(suffix) < 16:
                raise TokenError(f"Neovim: invalid terminal slot {target}")
            terminal[int(suffix)] = value
            continue
        match = GROUP.fullmatch(target)
        if match is None:
            raise TokenError(f"Neovim: invalid highlight target {target}")
        name, field = match.groups()
        group = groups.setdefault(name, {})
        group[field] = value
        if mapping[target] in ("semantic.color.syn-comment", "semantic.color.syn-keyword"):
            group["italic"] = True
    required = {"Normal", "NormalFloat", "Cursor", "TermCursor", "Visual", "Search", "IncSearch", "DiffAdd", "DiffDelete"}
    if not required <= groups.keys() or set(terminal) != set(range(16)):
        raise TokenError("Neovim: editor, float, cursor, selection/search/diff groups and all 16 ANSI slots are required")
    for name in required:
        if not {"fg", "bg"} <= groups[name].keys():
            raise TokenError(f"Neovim {name}: explicit foreground and background are required")
    for level, attribute in (("Error", "undercurl"), ("Warn", "underdashed"), ("Info", "underline"), ("Hint", "underdotted")):
        groups.setdefault("DiagnosticUnderline" + level, {})[attribute] = True
    for name in ("SpellBad", "SpellCap", "SpellLocal", "SpellRare"):
        groups.setdefault(name, {})["undercurl"] = True
    for name in ("Underlined", "@markup.link"):
        groups.setdefault(name, {})["underline"] = True
    return groups, [terminal[index] for index in range(16)]


def contrast(groups, terminal, mode):
    evidence = []
    normal = groups["Normal"]["bg"]
    for name, attributes in sorted(groups.items()):
        if "fg" not in attributes:
            continue
        backgrounds = [attributes.get("bg", normal)]
        if name.startswith("@") or name in ("Comment", "String", "Keyword", "Function", "Type", "Number"):
            backgrounds.append(groups["CursorLine"]["bg"])
        for background in dict.fromkeys(backgrounds):
            minimum = 3 if name in ("FloatBorder", "WinSeparator", "VertSplit") else 4.5
            if name in ("Comment", "@comment", "@comment.documentation") and background == normal:
                minimum = 7.5 if mode == "night" else 5
            ratio = contrast_value(color_from_hex(attributes["fg"]), color_from_hex(background))
            if ratio < minimum:
                raise TokenError(f"Neovim {name} [{mode}]: contrast {ratio:.6f} below {minimum}")
            evidence.append({"group": name, "foreground": attributes["fg"], "background": background,
                             "ratio": ratio, "minimum": minimum})
    for index, colour in enumerate(terminal):
        if index == 0 and mode != "day":
            continue
        ratio = contrast_value(color_from_hex(colour), color_from_hex(normal))
        if ratio < 4.5:
            raise TokenError(f"Neovim ANSI {index} [{mode}]: contrast {ratio:.6f} below 4.5")
        evidence.append({"group": f"terminal_color_{index}", "foreground": colour, "background": normal,
                         "ratio": ratio, "minimum": 4.5})
    for name in ("Cursor", "TermCursor"):
        ratio = contrast_value(color_from_hex(groups[name]["bg"]), color_from_hex(normal))
        if ratio < 3:
            raise TokenError(f"Neovim {name} [{mode}]: cursor contrast below 3")
        evidence.append({"group": name + " indicator", "foreground": groups[name]["bg"], "background": normal,
                         "ratio": ratio, "minimum": 3})
    return evidence


def lua(groups, terminal, mode, name):
    lines = ["-- Generated by Fjord. MIT; see LICENSE. Do not edit generated colours.",
             'if vim.fn.has("nvim-0.12") == 0 then error("Fjord requires Neovim 0.12 or later") end',
             "vim.g.colors_name = nil", f'vim.o.background = "{"light" if mode == "day" else "dark"}"',
             'vim.cmd("highlight clear")', "vim.o.termguicolors = true", f"vim.g.colors_name = {json.dumps(name + '-' + mode)}",
             "local groups = {"]
    for group, attributes in sorted(groups.items()):
        fields = ", ".join(f"{key} = {str(value).lower() if isinstance(value, bool) else json.dumps(value)}"
                           for key, value in sorted(attributes.items()))
        lines.append(f"  [{json.dumps(group)}] = {{ {fields} }},")
    lines += ["}", "for group, attributes in pairs(groups) do vim.api.nvim_set_hl(0, group, attributes) end",
              "local terminal = { " + ", ".join(map(json.dumps, terminal)) + " }",
              'for index, colour in ipairs(terminal) do vim.g["terminal_color_" .. (index - 1)] = colour end', ""]
    return "\n".join(lines)


def bundle(root=ROOT, theme=None, overrides=(), name="fjord"):
    root = Path(root)
    if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
        raise TokenError("Neovim colourscheme name must use lower-case letters, digits and hyphens")
    manifest = json.loads((root / "adapters/neovim/adapter.json").read_text())
    modes, report = map_adapter(root, "adapters/neovim/adapter.json", theme, overrides)
    files = {}
    for mode, values in modes.items():
        groups, terminal = highlights(values, manifest["mapping"])
        report["modes"][mode]["contrast"] = contrast(groups, terminal, mode)
        report["modes"][mode]["highlights"] = groups
        files[f"colors/{name}-{mode}.lua"] = lua(groups, terminal, mode, name)
    files[f"colors/{name}.lua"] = ('-- Follow the existing background preference. MIT.\n'
                                      f'vim.cmd.colorscheme(vim.o.background == "light" and "{name}-day" or "{name}-night")\n')
    for filename in ("README.md", "LICENSE"):
        files[filename] = (root / "adapters/neovim" / filename).read_text()
    files["report.json"] = json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--theme", type=Path)
    parser.add_argument("--override", type=Path, action="append", default=[])
    parser.add_argument("--name", default="fjord")
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args(argv)
    try:
        files = bundle(args.root, args.theme, args.override, args.name)
        destination = args.output_dir or args.root / "dist/adapters/neovim"
        write_adapter_files(args.root, destination, files, [*args.override] + ([args.theme] if args.theme else []))
        print(f"Built Neovim adapter: {destination}")
    except (TokenError, OSError, UnicodeError) as error:
        print(f"ERROR {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
